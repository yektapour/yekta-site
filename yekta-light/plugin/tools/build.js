// Builds dist/: Photoshop plugin folder + .ccx, desktop app source, web version.
// Also pre-renders model / preset icons into core/thumbs.js so the panel renders nothing at startup.
// Usage: node tools/build.js
const fs = require('fs'), path = require('path'), { execSync } = require('child_process');
const root = path.join(__dirname, '..'), core = path.join(root, 'core'), dist = path.join(root, 'dist');
const CORE = ['index.html', 'styles.css', 'color.js', 'png.js', 'render.js', 'mesh-head.js', 'mesh-headF.js', 'mesh-skull.js', 'mesh-bodyF.js', 'mesh-bodyM.js', 'mesh-heroF.js', 'mesh-heroM.js', 'thumbs.js', 'host.js', 'app.js', 'CREDITS.txt'];

global.window = {};
for (const f of ['color.js', 'png.js', 'render.js', 'mesh-head.js', 'mesh-headF.js', 'mesh-skull.js', 'mesh-bodyF.js', 'mesh-bodyM.js', 'mesh-heroF.js', 'mesh-heroM.js']) eval(fs.readFileSync(path.join(core, f), 'utf8'));
const Y = global.window.Yekta, R = Y.render;

// ---- thumbnails ----
const thumbs = { models: {}, presets: {} };
for (const m of R.models) {
  const st = R.defaultState();
  Object.assign(st, { model: m, rot: R.modelRot[m] || st.rot, compare: false, shadows: true });
  st.matA = Object.assign({}, st.matA, { base: [0.82, 0.8, 0.77], specInt: 0.2, gloss: 0.4 });
  st.ambient = { color: [0.55, 0.55, 0.6], intensity: 0.45, temp: 0.5 };
  thumbs.models[m] = Y.png.dataURL(48, 48, R.render(st, 48, 48, { ss: 3 }));
}
for (const p of R.presets) {
  const st = R.defaultState();
  Object.assign(st, { light: p.light, ambient: p.ambient, rim: p.rim, matA: Object.assign({}, st.matA, p.mat), compare: false, model: 'sphere' });
  if (p.bounce) st.bounce = p.bounce;
  thumbs.presets[p.name] = Y.png.dataURL(48, 48, R.render(st, 48, 48, { ss: 3 }));
}
fs.writeFileSync(path.join(core, 'thumbs.js'), '/* generated by tools/build.js */\n(function (L) { L.thumbs = ' + JSON.stringify(thumbs) + '; })((window.Yekta = window.Yekta || {}));\n');

function icon(n) {
  const st = R.defaultState();
  Object.assign(st, { compare: false, light: { ...st.light, intensity: 1.35, color: [1, 0.85, 0.6] }, rim: { color: [1, 0.75, 0.35], intensity: 0.5, width: 0.4 } });
  st.matA.base = [0.95, 0.72, 0.36];
  return Y.png.encode(n, n, R.render(st, n, n, { ss: 4 }));
}
const rm = (p) => fs.rmSync(p, { recursive: true, force: true });
const cp = (to) => { fs.mkdirSync(to, { recursive: true }); for (const f of CORE) fs.copyFileSync(path.join(core, f), path.join(to, f)); };

// keep packaged apps (*.zip) that are built separately
if (fs.existsSync(dist)) for (const f of fs.readdirSync(dist)) if (!f.endsWith('.zip')) rm(path.join(dist, f));
fs.mkdirSync(dist, { recursive: true });
const ps = path.join(dist, 'YektaLight-Photoshop');
cp(ps);
fs.copyFileSync(path.join(root, 'photoshop', 'manifest.json'), path.join(ps, 'manifest.json'));
fs.mkdirSync(path.join(ps, 'icons'));
for (const [name, n] of [['panel.png', 23], ['panel@2x.png', 46], ['plugin.png', 48], ['plugin@2x.png', 96]]) fs.writeFileSync(path.join(ps, 'icons', name), icon(n));
execSync('zip -qr ../YektaLight.ccx .', { cwd: ps });
const dk = path.join(dist, 'YektaLight-Desktop');
cp(path.join(dk, 'app'));
fs.writeFileSync(path.join(dk, 'app', 'icon.png'), icon(512));
for (const f of ['package.json', 'main.js', 'preload.js']) fs.copyFileSync(path.join(root, 'desktop', f), path.join(dk, f));
cp(path.join(dist, 'YektaLight-Web'));
console.log('built ->', dist);
